func TestCLI_Check(t *testing.T) {
	dir := t.TempDir()
	binary := filepath.Join(dir, "gotyper")
	if runtime.GOOS == "windows" {
		binary += ".exe"
	}
	build := exec.Command("go", "build", "-o", binary, "../..")
	output, err := build.CombinedOutput()
	require.NoError(t, err, "%s", output)

	for _, source := range []struct {
		name, input, declaration string
		args                     []string
		stdin                    bool
	}{
		{name: "sample", args: []string{"--input", "input.json"}, input: `[{"omega":{"id":2},"alpha":{"id":1},"created":"2023-01-15T14:30:00Z"}]`, declaration: "type Record struct"},
		{name: "multiple samples", args: []string{"--sample", "input.json", "--sample", "second.json"}, input: `{"id":1,"value":2}`, declaration: `json:"extra,omitempty"`},
		{name: "NDJSON file", args: []string{"--ndjson", "--input", "input.json"}, input: "{\"id\":1,\"value\":2}\n{\"id\":2,\"value\":2.5,\"extra\":\"new\"}\n", declaration: `json:"extra,omitempty"`},
		{name: "NDJSON samples", args: []string{"--ndjson", "--sample", "input.json", "--sample", "second.json"}, input: "{\"id\":1,\"value\":2}\n", declaration: `json:"extra,omitempty"`},
		{name: "NDJSON stdin", args: []string{"--ndjson"}, stdin: true, input: "{\"id\":1,\"value\":2}\n{\"id\":2,\"value\":2.5,\"extra\":\"new\"}\n", declaration: `json:"extra,omitempty"`},
		{name: "schema", args: []string{"--schema", "input.json"}, input: `{"type":"object","properties":{"omega":{"type":"integer"},"alpha":{"type":"string","format":"date-time"}}}`, declaration: "type Record struct"},
		{name: "schema root map", args: []string{"--schema", "input.json"}, input: `{"type":"object","additionalProperties":{"type":"integer"}}`, declaration: "type Record = map[string]int64"},
		{name: "schema root array", args: []string{"--schema", "input.json"}, input: `{"type":"array","items":{"type":"string"}}`, declaration: "type Record = []string"},
		{name: "schema root reference", args: []string{"--schema", "input.json"}, input: `{"$ref":"#/$defs/Node","$defs":{"Node":{"type":"object","properties":{"next":{"$ref":"#"}}}}}`, declaration: "type Record = Node"},
	} {
		for _, formatted := range []string{"true", "false"} {
			t.Run(source.name+"/format="+formatted, func(t *testing.T) {
				work := t.TempDir()
				require.NoError(t, os.WriteFile(filepath.Join(work, "input.json"), []byte(source.input), 0o644))
				require.NoError(t, os.WriteFile(filepath.Join(work, "second.json"), []byte(`{"id":2,"value":2.5,"extra":"new"}`), 0o644))
				require.NoError(t, os.WriteFile(filepath.Join(work, "config.yml"), []byte("package: models\nroot_name: Record\n"), 0o644))
				args := append(append([]string{}, source.args...), "--config", "config.yml", "--format="+formatted, "--output", "generated.go")
				run := func(args ...string) (string, string, error) {
					cmd := exec.Command(binary, args...)
					cmd.Dir = work
					if source.stdin {
						cmd.Stdin = strings.NewReader(source.input)
					}
					var stdout, stderr bytes.Buffer
					cmd.Stdout, cmd.Stderr = &stdout, &stderr
					err := cmd.Run()
					return stdout.String(), stderr.String(), err
				}

				stdout, stderr, err := run(args...)
				require.NoError(t, err, "%s", stderr)
				assert.Empty(t, stdout)
				path := filepath.Join(work, "generated.go")
				generated, err := os.ReadFile(path)
				require.NoError(t, err)
				assert.True(t, strings.HasPrefix(string(generated), "// Code generated by gotyper. DO NOT EDIT.\n\npackage models\n"))
				assert.Contains(t, string(generated), source.declaration)

				for range 10 {
					_, stderr, err = run(args...)
					require.NoError(t, err, "%s", stderr)
					repeated, err := os.ReadFile(path)
					require.NoError(t, err)
					assert.Equal(t, generated, repeated)
				}

				checkArgs := append(append([]string{}, args...), "--check")
				for _, stale := range []bool{false, true} {
					content := generated
					if stale {
						content = append([]byte("// Hand edit\n"), generated...)
					}
					require.NoError(t, os.WriteFile(path, content, 0o644))
					stamp := time.Unix(1234567890, 0)
					require.NoError(t, os.Chtimes(path, stamp, stamp))
					stdout, stderr, err = run(checkArgs...)
					if stale {
						require.Error(t, err)
						assert.Contains(t, stderr, "is stale")
					} else {
						require.NoError(t, err, "%s", stderr)
					}
					assert.Empty(t, stdout)
					after, readErr := os.ReadFile(path)
					require.NoError(t, readErr)
					assert.Equal(t, content, after)
					info, statErr := os.Stat(path)
					require.NoError(t, statErr)
					assert.Equal(t, stamp, info.ModTime())
				}

				require.NoError(t, os.Remove(path))
				stdout, stderr, err = run(checkArgs...)
				require.Error(t, err)
				assert.Contains(t, stderr, "is missing")
				assert.Empty(t, stdout)
				_, err = os.Stat(path)
				assert.True(t, os.IsNotExist(err))

				_, stderr, err = run(args...)
				require.NoError(t, err, "%s", stderr)
				restored, err := os.ReadFile(path)
				require.NoError(t, err)
				assert.Equal(t, generated, restored)
			})
		}
	}

	cmd := exec.Command(binary, "--check")
	cmd.Stdin = strings.NewReader("invalid JSON")
	output, err = cmd.CombinedOutput()
	require.Error(t, err)
	assert.Contains(t, string(output), "--check requires --output")

	t.Run("go generate", func(t *testing.T) {
		work := t.TempDir()
		require.NoError(t, os.Mkdir(filepath.Join(work, "models"), 0o755))
		require.NoError(t, os.WriteFile(filepath.Join(work, "go.mod"), []byte("module example.com/generated\n\ngo 1.25\n"), 0o644))
		require.NoError(t, os.WriteFile(filepath.Join(work, "models", "user.json"), []byte(`{"id":1,"name":"Example"}`), 0o644))
		directive := "package models\n\n//go:generate gotyper --input user.json --output user_generated.go --package models --root-name User\n"
		require.NoError(t, os.WriteFile(filepath.Join(work, "models", "generate.go"), []byte(directive), 0o644))
		cmd := exec.Command("go", "generate", "./models")
		cmd.Dir = work
		cmd.Env = append(os.Environ(), "PATH="+dir+string(os.PathListSeparator)+os.Getenv("PATH"))
		output, err := cmd.CombinedOutput()
		require.NoError(t, err, "%s", output)

		cmd = exec.Command(binary, "--input", "user.json", "--output", "user_generated.go", "--package", "models", "--root-name", "User", "--check")
		cmd.Dir = filepath.Join(work, "models")
		output, err = cmd.CombinedOutput()
		require.NoError(t, err, "%s", output)

		cmd = exec.Command("go", "test", "./models")
		cmd.Dir = work
		output, err = cmd.CombinedOutput()
		require.NoError(t, err, "%s", output)
	})
}

// TestCLI_FileInputOutput tests the CLI with file input and output
func TestCLI_FileInputOutput(t *testing.T) {
	// Create a temporary directory for test files
	tempDir, err := os.MkdirTemp("", "gotyper-test")
	require.NoError(t, err)
	defer func() {
		if err := os.RemoveAll(tempDir); err != nil {
			fmt.Fprintf(os.Stderr, "Error removing directory: %v\n", err)
		}
	}()
	// Create a test JSON file
	jsonContent := `{
		"name": "John Doe",
		"age": 30,
		"email": "john.doe@example.com",
		"address": {
			"street": "123 Main St",
			"city": "Anytown",
			"zip": "12345"
		},
		"phones": [
			{
				"type": "home",
				"number": "555-1234"
			},
			{
				"type": "work",
				"number": "555-5678"
			}
		],
		"active": true
	}`
	jsonFile := filepath.Join(tempDir, "test.json")
	err = os.WriteFile(jsonFile, []byte(jsonContent), 0o644)
	require.NoError(t, err)

	// Define output file path
	outputFile := filepath.Join(tempDir, "output.go")

	// Run the CLI command
	cmd := exec.Command("go", "run", "../../main.go", "-i", jsonFile, "-o", outputFile, "-p", "testpackage")
	output, err := cmd.CombinedOutput()
	require.NoError(t, err, "CLI command failed: %s", string(output))

	// Read the generated output file
	generatedCode, err := os.ReadFile(outputFile)
	require.NoError(t, err)

	// Verify the generated code
	code := string(generatedCode)
	assert.Contains(t, code, "package testpackage")
	assert.Contains(t, code, "type RootType struct")

	// Check for field presence without exact whitespace matching
	assert.Regexp(t, `Name\s+string\s+\x60json:"name"\x60`, code)
	assert.Regexp(t, `Age\s+int64\s+\x60json:"age"\x60`, code)
	assert.Regexp(t, `Email\s+string\s+\x60json:"email"\x60`, code)
	assert.Regexp(t, `Address\s+\*RootTypeAddress\s+\x60json:"address,omitempty"\x60`, code)
	assert.Regexp(t, `Phones\s+\*?\[?\]?\*?\[?\]?\*?RootTypePhone\s+\x60json:"phones,omitempty"\x60`, code)
	assert.Regexp(t, `Active\s+bool\s+\x60json:"active"\x60`, code)

	// Check for the nested Address struct
	assert.Contains(t, code, "type RootTypeAddress struct")
	assert.Regexp(t, `Street\s+string\s+\x60json:"street"\x60`, code)
	assert.Regexp(t, `City\s+string\s+\x60json:"city"\x60`, code)
	assert.Regexp(t, `Zip\s+string\s+\x60json:"zip"\x60`, code)

	// Check for the Phone struct
	assert.Contains(t, code, "type RootTypePhone struct")
	assert.Regexp(t, `Type\s+string\s+\x60json:"type"\x60`, code)
	assert.Regexp(t, `Number\s+string\s+\x60json:"number"\x60`, code)
}

// TestCLI_StdinStdout tests the CLI with stdin input and stdout output
